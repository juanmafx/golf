# Builds reports/tests/TEST_REPORT.md from the JUnit files of a real run.
import datetime
import pathlib
import sys
import xml.etree.ElementTree as ElementTree


def totals(path):
    root = ElementTree.parse(path).getroot()
    cases = list(root.iter("testcase"))
    failed = sum(1 for case in cases if case.find("failure") is not None or case.find("error") is not None)
    skipped = sum(1 for case in cases if case.find("skipped") is not None)
    return len(cases), len(cases) - failed - skipped, failed, skipped


def main():
    directory = pathlib.Path(sys.argv[1])
    php_image, node_image = sys.argv[2], sys.argv[3]
    suites = [("Backend (PHPUnit)", "backend-junit.xml", php_image), ("Frontend (Vitest)", "frontend-junit.xml", node_image)]
    lines = [
        "# Test Report",
        "",
        f"Generated by `scripts/run-tests.sh` on {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%d %H:%M} UTC.",
        "",
        "| Suite | Tests | Passed | Failed | Skipped | Runtime image |",
        "| --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for name, filename, image in suites:
        total, passed, failed, skipped = totals(directory / filename)
        lines.append(f"| {name} | {total} | {passed} | {failed} | {skipped} | `{image.split('@')[0]}` |")
    lines += ["", "Raw results: `backend-junit.xml` and `frontend-junit.xml`. Code coverage was not measured.", ""]
    (directory / "TEST_REPORT.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
